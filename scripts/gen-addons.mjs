// What the Studio app takes from the private addons that scripts/link-addon.mjs linked, written at prebuild so the
// app never names an addon in its source. With none linked (the open build) every output is the core's own.
//
//   apps/studio/src/addons.gen.ts            the slot contributions, each addon's studio.slots.ts (lazy imports only)
//   apps/studio/src/styles/addons.gen.css    @source lines so Tailwind sees the classes in each addon's UI
//   .studio-addons/project.inlang/           the inlang project with each addon's messages added (only when linked)
//
// An addon says what it brings in its package.json:
//   "studio": { "addon": "cloud", "slots": "./src/studio.slots.ts", "ui": "./src", "messages": "./messages/{locale}.json" }
// `slots` must be exported by the package as "./studio-slots".
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const app = join(root, 'apps/studio')
const state = join(root, '.studio-addons/addons.json')
const linked = existsSync(state) ? JSON.parse(readFileSync(state, 'utf8')).addons ?? [] : []

const write = (file, text) => {
  mkdirSync(dirname(file), { recursive: true })
  if (!existsSync(file) || readFileSync(file, 'utf8') !== text) writeFileSync(file, text)
}

const addons = linked.map(({ name, dir }) => {
  const manifest = JSON.parse(readFileSync(join(root, dir, 'package.json'), 'utf8'))
  if (!manifest.studio?.addon) throw new Error(`${name} is linked but its package.json has no "studio": { "addon": ... }`)
  return { name, dir: join(root, dir), ...manifest.studio }
})

const withSlots = addons.filter((a) => a.slots)
write(
  join(app, 'src/addons.gen.ts'),
  [
    '// Generated by scripts/gen-addons.mjs from the linked addons; do not edit.',
    "import type { RegisteredContribution } from '@pikkustudio/blocks/lib/studio-slots'",
    ...withSlots.map((a, i) => `import { contributions as addon${i} } from '${a.name}/studio-slots'`),
    '',
    'export const slotContributions: readonly RegisteredContribution[] = [',
    ...withSlots.map((a, i) => `  ...addon${i}.map((c) => ({ ...c, addon: ${JSON.stringify(a.addon)} })),`),
    ']',
    '',
  ].join('\n'),
)

const styles = join(app, 'src/styles')
write(
  join(styles, 'addons.gen.css'),
  ['/* Generated by scripts/gen-addons.mjs from the linked addons; do not edit. */', ...addons.filter((a) => a.ui).map((a) => `@source '${relative(styles, join(a.dir, a.ui))}';`), ''].join('\n'),
)

// The inlang project stays the committed one for the open build. With addons, a copy beside the linked state adds
// their message files, its paths made relative to where the copy lives.
const inlang = join(root, '.studio-addons/project.inlang')
const withMessages = addons.filter((a) => a.messages)
if (withMessages.length) {
  const settings = JSON.parse(readFileSync(join(app, 'project.inlang/settings.json'), 'utf8'))
  const format = settings['plugin.inlang.messageFormat']
  const rebase = (pattern) => './' + relative(dirname(inlang), resolve(app, pattern))
  format.pathPattern = [...format.pathPattern.map(rebase), ...withMessages.map((a) => './' + relative(dirname(inlang), join(a.dir, a.messages)))]
  write(join(inlang, 'settings.json'), JSON.stringify(settings, null, 2) + '\n')
}

console.log(addons.length ? `Studio app takes ${addons.map((a) => a.addon).join(', ')}` : 'Studio app takes no private addon')
